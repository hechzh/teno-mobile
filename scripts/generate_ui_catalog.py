"""Generate a source-label bridge from ARB; labels never translate API payloads."""
import json
from pathlib import Path

root=Path(__file__).resolve().parents[1]/'shared-ui/lib/l10n'
source=json.loads((root/'app_en.arb').read_text(encoding='utf-8'))
translated=json.loads((root/'app_zh.arb').read_text(encoding='utf-8'))
assert {k for k in source if not k.startswith('@')} == {k for k in translated if not k.startswith('@')}
lines=["// Generated by scripts/generate_ui_catalog.py from ARB. Do not edit.","import 'generated/app_localizations.dart';",'',
       'String lookupUiMessage(AppLocalizations l, String source) => switch (source) {']
for key,value in source.items():
    if key.startswith('@') or '{' in value:continue
    literal=json.dumps(value,ensure_ascii=False).replace('$',r'\$')
    lines.append(f'  {literal} => l.{key},')
lines+=['  _ => source,','};','']
(root/'ui_catalog.g.dart').write_text('\n'.join(lines),encoding='utf-8')
print(f'Generated {len(lines)-8} app-authored labels from ARB.')
