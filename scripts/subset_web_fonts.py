"""Reproducible Web-only CJK subsets (fonttools[woff]==4.61.1).

The native TTF stays intact. UI glyphs load at startup; common and remaining
glyphs are partitioned into small, disjoint assets for content/IME loading.
"""
import hashlib
import io
import json
from functools import lru_cache
from pathlib import Path
from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT/'web-client/assets/fonts/NotoSansSC-Regular.woff2'
OUTPUT = ROOT/'web-client/assets/fonts/subsets'
CACHED = {}


@lru_cache(maxsize=1)
def source_ttf():
    # WOFF2 table reconstruction is expensive in Python; do it once per run.
    font = TTFont(SOURCE, recalcTimestamp=False)
    font.flavor = None
    buffer = io.BytesIO()
    font.save(buffer)
    return buffer.getvalue()


def write_font(points, path):
    cached = CACHED.get(path.name)
    if (cached and set(map(ord, cached['chars'])) == points and path.is_file()
            and hashlib.sha256(path.read_bytes()).hexdigest() == cached['sha256']):
        return dict(cached)
    font = TTFont(io.BytesIO(source_ttf()), recalcTimestamp=False)
    options = subset.Options()
    options.flavor = 'woff2'
    options.recalc_timestamp = False
    options.name_IDs = ['*']
    options.name_legacy = True
    options.name_languages = ['*']
    worker = subset.Subsetter(options=options)
    worker.populate(unicodes=points)
    worker.subset(font)
    # Keep OFL attribution; do not use the upstream Reserved Font Name.
    for record in font['name'].names:
        if record.nameID in (1, 4, 6, 16):
            record.string = 'TenoCJKSubset'.encode(record.getEncoding())
    font.flavor = 'woff2'
    buffer = io.BytesIO()
    font.save(buffer)
    path.write_bytes(buffer.getvalue())
    return {'file': path.name, 'chars': ''.join(chr(c) for c in sorted(points)),
            'bytes': path.stat().st_size, 'sha256': hashlib.sha256(path.read_bytes()).hexdigest()}


def generate():
    OUTPUT.mkdir(parents=True, exist_ok=True)
    manifest_path = OUTPUT/'manifest.json'
    if manifest_path.is_file():
        old = json.loads(manifest_path.read_text(encoding='utf-8'))
        if old['source_sha256'] == hashlib.sha256(SOURCE.read_bytes()).hexdigest():
            CACHED.update({c['file']:c for c in [old['initial'], *old['chunks']]})
    supported = set(TTFont(SOURCE).getBestCmap())
    code = '\n'.join(p.read_text(encoding='utf-8') for folder in ['shared-ui/lib', 'web-client/lib'] for p in (ROOT/folder).rglob('*.dart'))
    ui = (set(range(256)) | {ord(c) for c in code if ord(c) > 127}
          | set(range(0x2000, 0x2070)) | set(range(0x3000, 0x3040))) & supported
    common = set()
    # GB2312 level one supplies a stable group of common simplified characters.
    for lead in range(0xB0, 0xD8):
        for trail in range(0xA1, 0xFF):
            try:
                common.add(ord(bytes([lead, trail]).decode('gb2312')))
            except (UnicodeDecodeError, TypeError):
                pass
    common = (common & supported) - ui
    initial = write_font(ui, OUTPUT/'ui.woff2')
    chunks = []
    for category, points in [('common', common), ('extended', supported - ui - common)]:
        values = sorted(points)
        for offset in range(0, len(values), 256):
            chunks.append(write_font(set(values[offset:offset + 256]), OUTPUT/f'{category}-{offset//256:03d}.woff2'))
    result = {'schema': 1, 'source_sha256': hashlib.sha256(SOURCE.read_bytes()).hexdigest(),
              'family': 'NotoSansSC', 'initial': initial, 'chunks': chunks}
    for chunk in chunks:
        chunk['family'] = 'TenoCJK'+chunk['file'].replace('.woff2', '').replace('-', '')
    (ROOT/'shared-ui/lib/ui/font_families_web.dart').write_text(
        '// Generated by scripts/subset_web_fonts.py; names do not eagerly load fonts.\n'
        'const tenoFontFallbacks = [\n  \'NotoSansSC\',\n'+''.join("  '"+c['family']+"',\n" for c in chunks)+'];\n', encoding='utf-8')
    (OUTPUT/'manifest.json').write_text(json.dumps(result, ensure_ascii=False, separators=(',', ':'))+'\n', encoding='utf-8')
    print(json.dumps({'initial_bytes': initial['bytes'], 'initial_glyphs': len(ui),
                      'chunks': len(chunks), 'complete_glyphs': len(supported),
                      'total_bytes': initial['bytes'] + sum(c['bytes'] for c in chunks)}))


if __name__ == '__main__':
    generate()
